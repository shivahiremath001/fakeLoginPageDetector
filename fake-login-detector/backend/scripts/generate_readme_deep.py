add()
add("Deploying high-performance asynchronous web security applications on Windows platforms presents unique OS-level concurrency challenges that were solved through dedicated architectural isolation.")
add()
add("### 8.1 The Windows Event Loop Conflict: Selector vs. Proactor")
add("1. **The Root Dilemma:** On Windows, Python provides two distinct asyncio event loop implementations:")
add("   - `_WindowsSelectorEventLoop`: Built on the WinSock `select()` API. Supports standard network sockets but **cannot** handle asynchronous subprocess pipes.")
add("   - `_WindowsProactorEventLoop`: Built on Windows I/O Completion Ports (IOCP). Fully supports asynchronous child process pipes, sockets, and timers.")
add("2. **The Uvicorn Conflict:** When Uvicorn runs on Windows (especially with `--reload` or default settings), it frequently establishes a `_WindowsSelectorEventLoop` on the main thread to ensure clean signal handling and socket reloads.")
add("3. **The Playwright Crash:** Playwright Python communicates with the underlying Chromium browser binary via standard I/O pipes (`stdin`, `stdout`, `stderr`). If Playwright is invoked inside a `_WindowsSelectorEventLoop`, it raises an immediate fatal exception:")
add("   `NotImplementedError` or `AssertionError: assert self._browser is not None`")
add()
add("### 8.2 Dedicated Background Worker Loop Architecture")
add("To guarantee that the application operates flawlessly regardless of whether Uvicorn, Gunicorn, Celery, or Pytest started with a Selector loop, `PageFetcher` in [fetcher.py](file:///c:/Users/SHIVA/Documents/FakeLoginPageDetector/fake-login-detector/backend/app/fetcher.py) implements dedicated event loop isolation:")
add()
add("```python")
add("class PageFetcher:")
add("    def __init__(self):")
add("        self._worker_loop = None")
add("        self._worker_thread = None")
add("        self._worker_ready = threading.Event()")
add("        self._init_lock = threading.Lock()")
add()
add("    def _ensure_worker(self):")
add("        with self._init_lock:")
add("            if self._worker_thread is not None and self._worker_thread.is_alive():")
add("                return")
add("            self._worker_ready.clear()")
add()
add("            def _worker_runner():")
add("                if sys.platform == 'win32':")
add("                    # Force IOCP Proactor loop for Playwright pipes")
add("                    loop = asyncio.WindowsProactorEventLoopPolicy().new_event_loop()")
add("                else:")
add("                    loop = asyncio.new_event_loop()")
add("                asyncio.set_event_loop(loop)")
add("                self._worker_loop = loop")
add("                self._lock = asyncio.Lock()")
add("                self._semaphore = asyncio.Semaphore(settings.max_concurrent_scans)")
add("                self._worker_ready.set()")
add("                loop.run_forever()")
add()
add("            thread = threading.Thread(target=_worker_runner, daemon=True, name='PlaywrightWorker')")
add("            thread.start()")
add("            self._worker_ready.wait()")
add("            self._worker_thread = thread")
add("```")
add()
add("### 8.3 Thread-Safe Coroutine Dispatching")
